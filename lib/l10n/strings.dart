/// Translates [key] into the app's current language, falling back to English.
String translate(String lang, String key, {Map<String, String>? params}) {
  var text = strings[lang]?[key] ?? strings['en']?[key] ?? key;
  params?.forEach((k, v) => text = text.replaceAll('{$k}', v));
  return text;
}

/// Widget-tree helper. Rebuilds when the language changes.
String t(BuildContext context, String key, {Map<String, String>? params}) {
  final lang = context.watch<AppState>().lang;
  return translate(lang, key, params: params);
}
